-- One live row per X (Twitter) Ads campaign PER AD ACCOUNT (LFXV2-2665).
--
-- ACCOUNT-SCOPED key, because X does not document its campaign ids as globally unique: every
-- campaign endpoint is accounts/:account_id/campaigns[/:campaign_id]
-- (https://docs.x.com/x-ads-api/campaign-management) and none reads a campaign without the
-- account. Keying on the account is exact either way (see 000045). The account is
-- result.AccountID — the result struct is marshalled UNTAGGED, so the key is the Go field name —
-- exactly as twitterCreationAccountID reads it (X has no URL fallback).
--
-- LEGACY ROWS. The key carries the account EXTRACTED from the row's result provenance JSON
-- (the field each dispatcher's *CreationAccountID reader uses). A row that records no account
-- yields NULL, and NULLs are distinct in a unique index, so such a row can never block a
-- legitimate binding — and AdoptCampaign separately refuses (409 AlreadyBound) to adopt an id that
-- a live account-less row already holds, so an unknown-account row cannot slip a second binding
-- through adoption either. Every current write path (create and adopt) stamps the account.
--
-- A SEPARATE index per provider, never a wider 000020/000042 predicate — see 000020 and the
-- LFXV2-3056 log entry: whether a global key is right is a per-provider question.
--
-- AdoptCampaign and UpsertCampaign classify its 23505 as ErrPlatformCampaignAlreadyBound
-- (isPlatformCampaignBindingViolation): adoption answers the "already bound to another brief"
-- 409, and a dispatch that resolved to an already-bound campaign is reported as that named
-- conflict with its claim retained.
--
-- status <> 'deleted' and platform_campaign_id IS NOT NULL for 000020's reasons.
--
-- CONCURRENTLY, one statement per file, no transaction, and NO `IF NOT EXISTS` — 000020's
-- reasons: a retry over an INVALID leftover must fail with 42P07, not record this version clean
-- over an index that enforces nothing.
--
-- DEPLOY RISK: if live rows already bind one upstream campaign twice, the build fails, Migrate
-- leaves version 46 recorded DIRTY, and every later boot refuses with ErrDirty. Recovery, in order:
--   1. fix the duplicate binding (soft-delete one of the rows: UPDATE campaigns SET
--      status = 'deleted' WHERE id = '<row id>');
--   2. DROP INDEX CONCURRENTLY uq_campaigns_twitter_campaign_live;  -- the INVALID leftover
--   3. force the version back to its predecessor with the golang-migrate CLI against the same
--      database (default schema_migrations table):
--        migrate -path internal/infrastructure/postgres/migrations -database "$DATABASE_URL" force 45
--      (forcing back ONE version replays only this single-statement migration — see
--      docs/knowledge/code/internal-infrastructure-postgres.md on why longer forces are unsafe);
--   4. re-run: restart the service, whose boot Migrate applies 46 again.
CREATE UNIQUE INDEX CONCURRENTLY uq_campaigns_twitter_campaign_live
    ON campaigns (platform, platform_campaign_id, (NULLIF(result ->> 'AccountID', '')))
    WHERE status <> 'deleted' AND platform_campaign_id IS NOT NULL AND platform = 'twitter-ads';
